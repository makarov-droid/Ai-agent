// ---------- Основной маршрут ----------
app.post('/api/chat', async (req, res) => {
  const { agentName, message } = req.body;
  if (!agentName || !message) {
    return res.status(400).json({ error: 'agentName and message required' });
  }

  // Если есть OpenAI – используем его
  if (openai) {
    try {
      const systemPrompt = agentPrompts[agentName] || `Ты — ${agentName}, полезный AI-ассистент.`;
      const completion = await openai.chat.completions.create({
        model: 'gpt-4o-mini',
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user', content: message }
        ],
        temperature: 0.7,
        max_tokens: 1000,
      });
      return res.json({ reply: completion.choices[0].message.content });
    } catch (error) {
      console.error('OpenAI error:', error);
      // fallback к заглушке
    }
  }

  // Иначе – умная заглушка с характером
  const reply = getRandomReply(agentName);
  setTimeout(() => res.json({ reply }), 600);
});

const PORT = process.env.PORT || 3000;
app.listen(PORT, () => {
  console.log(`Agent API running on port ${PORT}`);
  console.log(openai ? '  ✅ OpenAI mode active' : '  ℹ️  Mock mode (no API key)');
});
